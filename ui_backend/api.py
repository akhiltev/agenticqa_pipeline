"""FastAPI backend for the Agentic QA Pipeline demo UI (ui/).

Run: .venv\\Scripts\\python.exe -m uvicorn ui_backend.api:app --port 8090 --reload
(from the project root, with the venv activated / using its python).
"""
from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fastapi import FastAPI, HTTPException, Query  # noqa: E402
from fastapi.middleware.cors import CORSMiddleware  # noqa: E402
from fastapi.responses import FileResponse, StreamingResponse  # noqa: E402
from fastapi.staticfiles import StaticFiles  # noqa: E402
from pydantic import BaseModel  # noqa: E402

from config.settings import settings  # noqa: E402
from mcp_servers import graphify_mcp_server as graphify_tools  # noqa: E402
from ui_backend import (  # noqa: E402
    coverage_service,
    graph_service,
    reports_service,
    reset_service,
    run_service,
    state_service,
)


app = FastAPI(title="Agentic QA Pipeline - Demo UI Backend")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://127.0.0.1:5173"],
    allow_methods=["*"],
    allow_headers=["*"],
)

# Serves the real JaCoCo HTML report (sut/target/site/jacoco/index.html and
# its per-class/per-package pages) directly, since it's a genuinely better,
# more detailed view (line-by-line green/red source highlighting) than
# anything worth re-implementing in React - the Coverage tab embeds/links to
# it rather than duplicating it.
_jacoco_dir = settings.sut_dir / "target" / "site" / "jacoco"
_jacoco_dir.mkdir(parents=True, exist_ok=True)
app.mount("/api/jacoco/html", StaticFiles(directory=str(_jacoco_dir), html=True), name="jacoco-html")


@app.get("/api/health")
def health() -> dict:
    return {"ok": True}


# --- Graph -----------------------------------------------------------------


@app.get("/api/graph")
def get_graph(
    god_nodes: int = Query(8, ge=1, le=50),
    depth: int = Query(1, ge=0, le=3),
) -> dict:
    return graph_service.get_default_view(god_node_count=god_nodes, depth=depth)


@app.get("/api/graph/expand")
def expand_graph(node_id: str, depth: int = Query(1, ge=1, le=3)) -> dict:
    return graph_service.expand_subgraph([node_id], depth=depth)


@app.get("/api/graph/search")
def search_graph(q: str) -> list[dict]:
    return graph_service.find_node_id_by_label(q)


@app.get("/api/graph/by-class")
def get_graph_by_class(class_name: str, depth: int = Query(1, ge=0, le=3)) -> dict:
    return graph_service.get_view_for_class(class_name, depth=depth)


# --- Graphify actions (mirrors README's CLI workflow) -----------------------


@app.post("/api/graphify/rebuild")
async def graphify_rebuild() -> dict:
    """`graphify update . --no-cluster` (AST-only, fast, no LLM)."""
    return await asyncio.to_thread(graphify_tools.rebuild_graph)


@app.post("/api/graphify/cluster")
async def graphify_cluster() -> dict:
    """`graphify cluster-only .` (community detection + GRAPH_REPORT.md +
    graph.html). Slower - can take tens of seconds on the full SUT graph."""
    return await asyncio.to_thread(graphify_tools.cluster_only)


@app.get("/api/graphify/report")
def graphify_report() -> dict:
    """Returns GRAPH_REPORT.md content, if it has been generated by a
    prior /api/graphify/cluster call."""
    path = settings.graphify_out_dir / "GRAPH_REPORT.md"
    if not path.exists():
        raise HTTPException(status_code=404, detail="GRAPH_REPORT.md not generated yet - run cluster first.")
    return {"content": path.read_text(encoding="utf-8")}


@app.get("/api/graphify/html-url")
def graphify_html_url() -> dict:
    """Whether graph.html exists, so the frontend can offer to open it
    (served as a static file - see graphify_html mount below)."""
    path = settings.graphify_out_dir / "graph.html"
    return {"exists": path.exists(), "url": "/api/graphify/html" if path.exists() else None}


@app.get("/api/graphify/html")
def graphify_html():
    path = settings.graphify_out_dir / "graph.html"
    if not path.exists():
        raise HTTPException(status_code=404, detail="graph.html not generated yet - run cluster first.")
    return FileResponse(path, media_type="text/html")


